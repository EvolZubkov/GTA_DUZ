// Основной сигнал — не наличие тачскрина (у многих ноутбуков он тоже есть),
// а то, что ОСНОВНОЙ указатель ввода неточный ("coarse") — это именно то,
// что отличает телефон/планшет без мыши от десктопа. matchMedia(pointer:
// coarse) — стандартный способ это проверить, шире поддерживается и
// надёжнее, чем эвристики по ширине экрана или user-agent.
export function isTouchDevice() {
  return window.matchMedia('(pointer: coarse)').matches;
}
